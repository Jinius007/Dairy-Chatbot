export function normalizeVobizLang(code?: string | null): VobizLang {
  const raw = String(code || "hi").toLowerCase().replace(/[^a-z]/g, "").slice(0, 4);
  if ((VOBIZ_LANGS as readonly string[]).includes(raw)) return raw as VobizLang;
  return "hi";
}

export function vobizPhraseText(key: VobizPhraseKey, lang?: string | null): string {
  const l = normalizeVobizLang(lang);
  const row = PHRASES[key];
  return row[l] || row.hi || row.en;
}
